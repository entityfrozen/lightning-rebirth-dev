import React, { useEffect, useRef, useState } from 'react';
import { api } from './constants.js';
import { Icon } from './icons.jsx';

const starters=[
  'Help me come up with a game idea',
  'Explain something difficult simply',
  'Write a short creative story',
  'Review my JavaScript code'
];
export function AI({user,onAuth}){
  const [status,setStatus]=useState({configured:false});
  const [conversation,setConversation]=useState([]);
  const [draft,setDraft]=useState('');
  const [sending,setSending]=useState(false);
  const [error,setError]=useState('');
  const bottom=useRef(null);
  useEffect(()=>{api('/api/ai/status').then(setStatus).catch(()=>{});},[]);
  useEffect(()=>bottom.current?.scrollIntoView({behavior:'smooth',block:'nearest'}),[conversation.length,sending]);
  const submit=async(event,example)=>{
    event?.preventDefault();
    const text=(example||draft).trim();
    if(!text||sending)return;
    if(!user){onAuth('login');return;}
    if(!status.configured){setError('The server needs an AI provider API key before messages can be sent.');return;}
    const next=[...conversation,{role:'user',content:text}];
    setConversation(next);setDraft('');setSending(true);setError('');
    try{
      const result=await api('/api/ai',{method:'POST',body:JSON.stringify({messages:next.slice(-14)})});
      setConversation(previous=>[...previous,{role:'assistant',content:result.text||'No response was returned.'}]);
    }catch(err){setError(err.message);}
    finally{setSending(false);}
  };
  return <div className="screen ai-screen">
    <div className="screen-head"><div><span className="eyebrow">CELESTIAL INTELLIGENCE</span><h1>Meet your <em>copilot.</em></h1><p>Ideas, answers and creative energy in one conversation.</p></div><span className={'head-side '+(status.configured?'online':'offline')}><i className="online-dot"/>{status.configured?'PROVIDER CONNECTED':'PROVIDER NOT CONFIGURED'}</span></div>
    <div className="ai-layout">
      <aside className="ai-side glass"><span className="micro">YOUR WORKSPACE</span>
        <button className="secondary-btn full" onClick={()=>{setConversation([]);setError('');}}>＋ New conversation</button>
        <div className="ai-side-separator"/>
        <span className="micro">STARTER IDEAS</span>
        {starters.map(text=><button className="starter" key={text} onClick={()=>submit(null,text)}>{text} <span>↗</span></button>)}
        <div className="ai-side-foot"><span>✧</span><strong>AI that works for you.</strong><p>Responses are generated by the server-side AI provider when configured. Conversations remain in this tab.</p></div>
      </aside>
      <section className="ai-panel glass">
        <div className="ai-panel-top"><strong><span>✧</span> Celestial AI</strong><span>{status.configured?'READY TO CREATE':'AWAITING SERVER CONNECTION'}</span></div>
        <div className="ai-message-list">
          {conversation.length===0?<div className="ai-welcome"><div className="ai-core">✧<div className="ai-orbit"/></div><span className="micro">THE NEXT IDEA STARTS HERE</span><h2>What are we <em>creating?</em></h2><p>Write a question, share a challenge or pick a starter prompt.</p>
            {!status.configured&&<div className="provider-warning"><span>◈</span> AI is not connected. Set <code>OPENAI_API_KEY</code> on the server to enable real responses.</div>}
          </div>:conversation.map((message,i)=><div key={i} className={'ai-message '+message.role}>
            {message.role==='assistant'&&<span className="ai-message-star">✧</span>}
            <div>{message.content}</div>
          </div>)}
          {sending&&<div className="ai-thinking"><span>✧</span> Generating response<span className="typing-dots">···</span></div>}
          <div ref={bottom}/>
        </div>
        <form className="ai-composer" onSubmit={submit}>
          <textarea value={draft} onChange={e=>setDraft(e.target.value)} aria-label="Message Celestial AI" rows={2} placeholder={status.configured?'Ask Celestial anything…':'Connect an AI provider to send a message'} onKeyDown={e=>{if(e.key==='Enter'&&!e.shiftKey){e.preventDefault();submit(e);}}}/>
          <button type="submit" className="primary-btn" disabled={sending||!draft.trim()||!status.configured} aria-label="Send to AI"><Icon name="send" size={17}/></button>
        </form>
        {error&&<div className="ai-error" role="alert">{error}</div>}
        <p className="ai-disclaimer">AI can make mistakes. Verify important information.</p>
      </section>
    </div>
  </div>;
}
